def extract_prompt(title: str, text: str, part: int, total: int) -> str:
    return EXTRACT.format(title=title, text=text, part=part, total=total)


def review_prompt(title: str, context: str, reqs: list[dict]) -> str:
    return REVIEW.format(criteria=criteria_text(INDIVIDUAL), sev=CRITICAL_HINT, title=title,
                         context=context, reqs=json.dumps(reqs, ensure_ascii=False, indent=1))


def set_prompt(title: str, doc: str, reqs: list[dict]) -> str:
    lines = "\n".join(f"- {r['id']} ({r.get('doc_id') or 'без ID'}; L{r['g1']}): {r['text']}" for r in reqs)
    return SET_REVIEW.format(criteria=criteria_text(SET), sev=CRITICAL_HINT, title=title, doc=doc, reqs=lines)
