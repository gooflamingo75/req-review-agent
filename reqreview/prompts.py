def extract_prompt(title: str, text: str, part: int, total: int) -> str:
    return EXTRACT.format(title=title, text=text, part=part, total=total)


def review_prompt(title: str, context: str, reqs: list[dict]) -> str:
    return REVIEW.format(criteria=criteria_text(INDIVIDUAL), sev=CRITICAL_HINT, tags=TAGS_HINT, title=title,
                         context=context, reqs=json.dumps(reqs, ensure_ascii=False, indent=1))


def _common(title: str, doc: str, reqs: list[dict], hints: list[str]) -> str:
    lines = "\n".join(f"- {r['id']} ({r.get('doc_id') or 'без ID'}; L{r['g1']}): {r['text']}" for r in reqs)
    return COMMON.format(hints="\n".join(f"- {h}" for h in hints) or "- нет", reqs=lines, title=title, doc=doc)


def set_prompt(part: str, title: str, doc: str, reqs: list[dict], hints: list[str]) -> str:
    tpl = SET_CONSISTENCY if part == "consistency" else SET_COMPLETENESS
    return tpl.format(criteria=criteria_text(SET), sev=CRITICAL_HINT, tags=TAGS_HINT,
                      common=_common(title, doc, reqs, hints))

